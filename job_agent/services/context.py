from __future__ import annotations

from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Protocol

from ..store import Store
from ..types import HTTPClient, Record


class AgentContext(Protocol):
    root: Path
    settings: Record
    profile: Record
    store: Store
    http: HTTPClient

    def close(self) -> None: ...
    def active(self) -> None: ...
    def resume_for(self, job: Record) -> Record: ...
    def resume(self) -> Record: ...
    def preflight(self) -> Record: ...
    def import_jobs(self, document: Record | list[Record]) -> list[tuple[str, bool]]: ...
    def prepare(self) -> list[Record]: ...
    def discover(self) -> Record: ...
    def _discover(self, run_id: str) -> Record: ...
    def _source_failed(self, source: Record) -> None: ...
    def review_queue(self, limit: int = 20) -> Record: ...
    def daily(self) -> Record: ...
    def merge_discovery(self, leads: Iterable[Record]) -> Iterator[Record]: ...
    def report(self) -> Record: ...
    def review_hash(self, row: Record) -> str: ...
    def deliver(self, report_id: str) -> Record: ...
    def scope_hash(self, row: Record, channel: str) -> str: ...
    def approve(self, job_id: str, channels: list[str]) -> Record: ...
    def accept_salary_exception(self, job_id: str) -> None: ...
    def refresh_for_execution(self, row: Record) -> Record: ...
    def handoff(self, job_id: str, channel: str) -> Record: ...
    def record_result(
        self, token: str, outcome: str, evidence: str | None = None, occurred_at: str | None = None
    ) -> Record: ...
    def reconcile_state(self, number: int) -> None: ...
    def follow_up_eligible(self, row: Record) -> None: ...
    def status(self) -> Record: ...
    def weekly_summary(self, rows: list[Record]) -> Record: ...
    def fetch_board(self, source: Record, http: HTTPClient | None = None) -> list[Record]: ...
